import sys,os,json,base64,io
from PIL import Image
os.chdir(os.path.dirname(os.path.abspath(__file__)))
order=json.load(open('out/_all.json'))
out=['/* Heartline pixel backgrounds (generated by pixel-studio/src/bg) */\n(window.PXBG=window.PXBG||{});\n']
tot=0;done=[]
for n in order:
    fs=[f'out/{n}_{i}.png' for i in range(4)]
    if not all(os.path.exists(f) for f in fs): continue
    ims=[Image.open(f).convert('RGB') for f in fs]
    sheet=Image.new('RGB',(480,270*4))
    for i,im in enumerate(ims): sheet.paste(im,(0,270*i))
    q=sheet.quantize(colors=int(os.environ.get('NC','64')),method=Image.MEDIANCUT,dither=Image.NONE)
    urls=[];sz=0
    for i in range(4):
        fr=q.crop((0,270*i,480,270*(i+1)))
        bio=io.BytesIO();fr.save(bio,'PNG',optimize=True);d=bio.getvalue();sz+=len(d)
        urls.append('data:image/png;base64,'+base64.b64encode(d).decode())
        fr.convert('RGB').save(f'out/q_{n}_{i}.png')
    tot+=sz;done.append((n,sz))
    out.append("window.PXBG['%s']={w:480,h:270,fps:4,frames:%s};\n"%(n,json.dumps(urls)))
open('/home/user/random/heartline/js/px/bg.js','w').write(''.join(out))
print(len(done),'bgs',tot//1024,'KB'); print(' '.join('%s:%d'%(n,s//1024) for n,s in done))
